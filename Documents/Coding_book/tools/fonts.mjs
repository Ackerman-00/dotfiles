#!/usr/bin/env node
// fonts.mjs — self-hosts the Google Fonts used by the site (latin subsets
// only; course content is English). Writes woff2 files to assets/fonts/ and
// an @font-face stylesheet to assets/css/fonts.css with RELATIVE urls so the
// build (protect.mjs) can merge it into a single app.css safely.
// Usage: node tools/fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT_FONTS = path.join(ROOT, 'assets/fonts');
const OUT_CSS = path.join(ROOT, 'assets/css/fonts.css');

const FAMILIES = [
  'family=Fraunces:ital,opsz,wght@0,9..144,400;0,9..144,500;0,9..144,600;1,9..144,400;1,9..144,500',
  'family=Geist+Mono:wght@400;500;600',
  'family=Inter:wght@400;500;600;700;800'
];
const URL = 'https://fonts.googleapis.com/css2?' + FAMILIES.join('&') + '&display=swap';

fs.mkdirSync(OUT_FONTS, { recursive: true });

const res = await fetch(URL, { headers: { 'user-agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36' } });
if (!res.ok) throw new Error('css2 fetch failed: ' + res.status);
const css = await res.text();

// split into [subset, block] pairs
const pairs = [];
const re = /\/\*\s*([a-z-]+)\s*\*\/\s*@font-face\s*\{([^}]+)\}/g;
let m;
while ((m = re.exec(css))) pairs.push([m[1], m[2]]);
if (!pairs.length) throw new Error('no @font-face rules parsed');

const latin = pairs.filter(p => p[0] === 'latin');
console.log(`parsed ${pairs.length} subsets (latin: ${latin.length})`);

const outRules = [];
for (const [, body] of latin){
  const fam = (body.match(/font-family:\s*'([^']+)'/) || [])[1];
  const w = (body.match(/font-weight:\s*(\d+)/) || [])[1];
  const style = (body.match(/font-style:\s*(\w+)/) || [])[1] || 'normal';
  const src = body.match(/url\(([^)]+)\)/);
  if (!fam || !w || !src) throw new Error('unparsable rule: ' + body.slice(0, 80));
  const slug = fam.replace(/[^a-z0-9]/gi, '').toLowerCase() + '-' + w + (style === 'italic' ? '-i' : '') + '.woff2';
  const buf = await (await fetch(src[1])).arrayBuffer();
  fs.writeFileSync(path.join(OUT_FONTS, slug), Buffer.from(buf));
  outRules.push(`@font-face{font-family:'${fam}';font-style:${style};font-weight:${w};font-display:swap;src:url(../fonts/${slug}) format('woff2')}`);
  console.log(`  ${slug} (${(buf.byteLength / 1024).toFixed(0)}KB)`);
}

fs.writeFileSync(OUT_CSS, '/* self-hosted fonts — generated by tools/fonts.mjs; relative urls keep the merged app.css valid */\n' + outRules.join('\n') + '\n');
console.log('wrote assets/css/fonts.css (' + outRules.length + ' faces)');
