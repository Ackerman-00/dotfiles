#!/usr/bin/env node
// ============================================================
// protect.mjs — builds the protected dist/ copy of the site.
//   · strips ALL comments (string/regex/template aware)
//   · collapses indentation, blank lines and double spaces
//   · keeps every newline + line terminators inside multi-line
//     comments, so ASI can never change behavior — the output
//     parses to the same program
//   · BUNDLES the 59 scripts (in index.html order) into ONE
//     assets/js/bundle.js and merges the 3 stylesheets into ONE
//     assets/css/app.css — kills 58 render-blocking requests
//   · security.js stays a separate file (loaded last)
//   · verifies the bundle with `node --check`
//   · runs the full smoke suite against dist/ (RZ_BASE=dist)
//   · writes NO source maps and NO human-readable markers
// Usage: node tools/protect.mjs
// ============================================================
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const BANNER = '/* Learn to Code from Zero — protected build. Generated by tools/protect.mjs. Do not edit. */\n';
const SCRIPT_RE = /<script(?:\s+src="([^"]*)")?\s*>/g;
const CSS_RE = /<link rel="stylesheet" href="assets\/css\/[^"]+">/g;

const KEYWORD_BEFORE_REGEX = new Set(['return','case','typeof','instanceof','in','of','new','void','do','else','yield','await','delete']);
const REGEX_PREV = new Set(['(','[','{',':',';',',','=','!','&','|','?','+','-','*','%','^','~','<','>']);

// ---- scanner: strips comments, collapses whitespace, preserves ASI ----
// Recursive-descent version: strings, template literals (with nested
// ${...} AND object-literal braces inside them), regexes and comments
// are each skipped by a dedicated routine, so a `}` can never desync
// the template tracker (the old flat tpl-counter broke on code like
// `${Array.from({length: n}, ...)}` and ate real code as comments).
function transform(src){
  const out = [];
  let i = 0; const n = src.length;
  let lastSig = '', lastWord = '';

  const flushLine = () => {
    while (out.length && (out[out.length - 1] === ' ' || out[out.length - 1] === '\n')) out.pop();
  };
  function skipString(qq){
    out.push(qq); i++;
    while (i < n){
      const c = src[i], c2 = i + 1 < n ? src[i + 1] : '';
      out.push(c);
      if (c === '\\'){ if (c2){ out.push(c2); i += 2; } else i++; continue; }
      i++;
      if (c === qq) break;
    }
  }
  function skipTemplate(){
    out.push('`'); i++;
    while (i < n){
      const c = src[i], c2 = i + 1 < n ? src[i + 1] : '';
      if (c === '\\'){ out.push(c); if (c2){ out.push(c2); i += 2; } else i++; continue; }
      if (c === '$' && c2 === '{'){ out.push(c); out.push(c2); i += 2; scanLevel(false); continue; }
      out.push(c); i++;
      if (c === '`') break;
    }
  }
  function skipRegexBody(){
    while (i < n){
      const c = src[i], c2 = i + 1 < n ? src[i + 1] : '';
      out.push(c);
      if (c === '\\'){ if (c2){ out.push(c2); i += 2; } else i++; continue; }
      if (c === '['){
        i++;
        while (i < n){
          const d = src[i], d2 = i + 1 < n ? src[i + 1] : '';
          out.push(d);
          if (d === '\\'){ if (d2){ out.push(d2); i += 2; } else i++; continue; }
          i++;
          if (d === ']') break;
        }
        continue;
      }
      i++;
      if (c === '/') break;
    }
    while (i < n && /[a-z]/i.test(src[i])) out.push(src[i++]);
  }
  function skipBlockCom(){
    i += 2;
    let hasNL = false;
    while (i < n && !(src[i] === '*' && i + 1 < n && src[i + 1] === '/')){
      if (src[i] === '\n') hasNL = true;
      i++;
    }
    i = Math.min(i + 2, n);
    if (hasNL){ flushLine(); out.push('\n'); lastSig = '\n'; }
  }
  function scanLevel(top){
    while (i < n){
      const c = src[i], c2 = i + 1 < n ? src[i + 1] : '';
      if (c === "'" || c === '"'){ skipString(c); continue; }
      if (c === '`'){ skipTemplate(); continue; }
      if (c === '/' && c2 === '/'){
        while (i < n && src[i] !== '\n') i++;
        continue;
      }
      if (c === '/' && c2 === '*'){ skipBlockCom(); continue; }
      if (c === '/'){
        const isRegex = lastSig === '' || lastSig === '\n' || REGEX_PREV.has(lastSig) ||
          (lastWord.length && KEYWORD_BEFORE_REGEX.has(lastWord));
        out.push(c);
        i++;
        if (isRegex) skipRegexBody();
        continue;
      }
      if (c === '{'){ out.push(c); lastSig = c; lastWord = ''; i++; scanLevel(false); continue; }
      if (c === '}'){
        out.push(c); lastSig = c; lastWord = ''; i++;
        if (!top) return;
        continue;
      }
      if (c === ' ' || c === '\t' || c === '\r' || c === '\n'){
        if (c === '\n'){
          flushLine();
          if (out.length){ out.push('\n'); lastSig = '\n'; lastWord = ''; }
          i++;
          continue;
        }
        if (out.length && out[out.length - 1] !== ' ' && out[out.length - 1] !== '\n'){ out.push(' '); lastSig = ' '; }
        i++;
        continue;
      }
      out.push(c);
      lastSig = c;
      if (/[A-Za-z_$]/.test(c)) lastWord += c; else lastWord = '';
      i++;
    }
  }
  scanLevel(true);
  flushLine();
  return out.join('');
}

// ---- mirror everything EXCEPT assets/js (rebuilt as one bundle) ----
if (fs.existsSync(DIST)) fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });

function walk(dir, rel){
  for (const name of fs.readdirSync(dir, { withFileTypes: true })){
    if (name.name === 'tools' || name.name === 'dist' || name.name === 'node_modules' || name.name === '.git' ||
        rel === 'assets/js') continue;
    const src = path.join(dir, name.name);
    const dstRel = rel ? rel + '/' + name.name : name.name;
    if (name.isDirectory()) walk(src, dstRel);
    else {
      if (/^assets\/css\/(base|fonts|widgets)\.css$/.test(dstRel)) continue;  // merged into hashed app.css
      const outPath = path.join(DIST, dstRel);
      fs.mkdirSync(path.dirname(outPath), { recursive: true });
      fs.copyFileSync(src, outPath);
    }
  }
}
walk(ROOT, '');

// ---- bundle: scripts in index.html order, security.js kept separate ----
const htmlSrc = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');
const scriptNames = [];
let sm;
SCRIPT_RE.lastIndex = 0;
while ((sm = SCRIPT_RE.exec(htmlSrc))){ if (sm[1]) scriptNames.push(sm[1]); }

const bundleParts = [];
let bundleCount = 0;
for (const name of scriptNames){
  if (name === 'assets/js/security.js') continue;
  const code = fs.readFileSync(path.join(ROOT, name), 'utf8');
  bundleParts.push(transform(code));
  bundleCount++;
}
const bundle = BANNER + bundleParts.join('\n;\n') + '\n';
fs.mkdirSync(path.join(DIST, 'assets/js'), { recursive: true });
// content-hashed filename: /assets/* is cached immutable (1 year) in
// _headers, so a stable name would pin every returning visitor to the
// FIRST deployed bundle forever. Same bytes → same name → cache is safe.
const hashName = (name, content) => {
  const h = createHash('sha256').update(content).digest('hex').slice(0, 12);
  const i = name.lastIndexOf('.');
  return name.slice(0, i) + '.' + h + name.slice(i);
};
const bundleName = hashName('bundle.js', bundle);
fs.writeFileSync(path.join(DIST, 'assets/js', bundleName), bundle);
execSync('node --check "' + path.join(DIST, 'assets/js', bundleName) + '"', { stdio: 'inherit' });
// security.js is ALSO content-hashed so the immutable /assets/* cache (1yr)
// can never serve a stale anti-inspect guard after an update — both JS files
// get a new filename on every build, exactly like the CSS bundle above.
const secSrc = fs.readFileSync(path.join(ROOT, 'assets/js/security.js'), 'utf8');
const secName = hashName('security.js', secSrc);
fs.writeFileSync(path.join(DIST, 'assets/js', secName), secSrc);
console.log(`PROTECT BUNDLE OK — ${bundleCount} scripts + security.js → assets/js/${bundleName} + ${secName} (${(bundle.length / 1024).toFixed(0)}KB), node --check passed`);

// ---- css: merge fonts + base + themes (registry + every theme in themes/) + widgets into one hashed app.css (same dir → relative font urls stay valid) ----
const cssFiles = [
  'assets/css/fonts.css',
  'assets/css/base.css',
  'assets/css/themes.css',
  ...fs.readdirSync(path.join(ROOT, 'assets/css/themes')).filter(f => f.endsWith('.css')).sort().map(f => 'assets/css/themes/' + f),
  'assets/css/widgets.css'
];
const appCss = cssFiles.map(f => fs.readFileSync(path.join(ROOT, f), 'utf8')).join('\n');
const cssName = hashName('app.css', appCss);
fs.mkdirSync(path.join(DIST, 'assets/css'), { recursive: true });
fs.writeFileSync(path.join(DIST, 'assets/css', cssName), appCss);
console.log(`PROTECT CSS OK — ${cssFiles.length} sheets (incl. themes/) → assets/css/${cssName}`);

// ---- dist/index.html: 3 css links → 1 hashed link, 59 script tags → hashed bundle + security ----
let distHtml = htmlSrc.replace(CSS_RE, `<link rel="stylesheet" href="assets/css/${cssName}">`);
distHtml = distHtml.replace(/(?:\s*<link rel="stylesheet" href="assets\/css\/[^"]+">)+/, `\n<link rel="stylesheet" href="assets/css/${cssName}">`);
distHtml = distHtml.replace(/<script src="assets\/js\/[^"]+"><\/script>\s*/g, '');
distHtml = distHtml.replace('</body>', `<script src="assets/js/${bundleName}"></script>\n<script src="assets/js/${secName}"></script>\n</body>`);
fs.writeFileSync(path.join(DIST, 'index.html'), distHtml);
const distScripts = (distHtml.match(/<script src="/g) || []).length;
const distCss = (distHtml.match(/<link rel="stylesheet" href=/g) || []).length;
console.log(`PROTECT HTML OK — dist/index.html: ${distScripts} script tags, ${distCss} css links (was 59 / 3)`);

// ---- semantic gate: full smoke suite against dist ----
try {
  execSync('node tools/smoke.mjs', { cwd: ROOT, env: { ...process.env, RZ_BASE: DIST }, stdio: 'inherit' });
  console.log('PROTECT VERIFY OK — dist/ passes the full smoke suite');
} catch(e){
  console.error('PROTECT VERIFY FAILED — dist/ is not behavior-identical. Aborting; dist/ kept for inspection.');
  process.exit(1);
}
